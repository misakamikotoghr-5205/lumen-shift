export const levels = specs.map(
  ([
    id,
    name,
    note,
    width,
    emitter,
    masks,
    turns,
    targetOffsets,
    locked,
    checkpoints,
  ]) => {
    const level = {
      id,
      name,
      note,
      width,
      emitter,
      masks,
      turns,
      locked,
      targets: {},
    };
    const targets = signals(level, targetOffsets);
    level.targets = Object.fromEntries(
      checkpoints.map((row) => [row, targets[row]]),
    );
    return Object.freeze(level);
  },
);
